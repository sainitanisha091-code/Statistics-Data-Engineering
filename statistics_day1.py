import numpy as np 
data = np.array([10,20,30,40,50])

mean = np.mean(data)
print(mean)

median = np.median(data)
print(median)

varience = np.var(data)
print(varience)

standard_deviation = np.std(data)
print(standard_deviation)

minimum = np.min(data)
print(minimum)

maximum = np.max(data)
print(maximum)

sum = np.sum(data)
print(sum)

length = len(data)
print(length)